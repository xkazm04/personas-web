/** What the desktop app knows about setting up one connector. Generated JSON, see scripts/sync-connector-setup.mjs. */
export interface ConnectorSetupField {
  label: string;
  /** "secret" is a masked credential; the others are plain inputs. Values are never stored. */
  kind: "secret" | "text" | "url" | "choice" | string;
  optional?: boolean;
  help?: string;
}

export interface ConnectorSetup {
  fields?: ConnectorSetupField[];
  /** The desktop's numbered guide, one entry per step (an un-numbered note stays one entry). */
  guide?: string[];
  docsUrl?: string;
  /** The connector can send but not read (e.g. an incoming webhook). */
  outboundOnly?: boolean;
}

export async function loadConnectorSetup(name: string): Promise<ConnectorSetup | null> {
  // The JSON is generated by sync-connector-setup.mjs, whose output shape is exactly ConnectorSetup keyed by connector name.
  const mod = (await import("./connector-setup.json")) as unknown as { default: Record<string, ConnectorSetup> };
  return mod.default[name] ?? null;
}
