#!/usr/bin/env node
/**
 * Projects the canonical agent guidance (.claude/CLAUDE.md) into the files that
 * agents other than Claude Code read on their own: GitHub Copilot
 * (.github/copilot-instructions.md) and Cursor (.cursor/rules/personas-web.mdc).
 *
 * A hand-written copy for each agent would drift from the canonical file the
 * first time a rule changed. These are generated instead. Each one carries the
 * canonical Project and Commands sections word for word and an index of the
 * numbered conventions, and points back at the canonical file for the rules
 * themselves. src/lib/guidanceProjections.test.ts holds every projection equal
 * to this script's output, so an edit to either side without a re-run fails
 * `test:unit`.
 *
 *   node scripts/project-guidance.mjs          rewrite the projections
 *   node scripts/project-guidance.mjs --check  exit 1 when a projection is stale
 *
 * The root AGENTS.md is not projected here: Next 16.3 regenerates it on every
 * `next dev`, and the repository gitignores it.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

export const CANONICAL = ".claude/CLAUDE.md";

/** @type {{ file: string, frontmatter: string[] }[]} */
export const PROJECTIONS = [
  { file: ".github/copilot-instructions.md", frontmatter: [] },
  {
    file: ".cursor/rules/personas-web.mdc",
    frontmatter: [
      "---",
      `description: personas-web agent guidance, projected from ${CANONICAL}`,
      "alwaysApply: true",
      "---",
    ],
  },
];

/**
 * The lines of one `## ` section, heading included, trailing blank lines dropped.
 *
 * @param {string[]} lines
 * @param {string} heading
 * @returns {string[]}
 */
export function sectionLines(lines, heading) {
  const start = lines.indexOf(heading);
  if (start === -1) throw new Error(`${CANONICAL} has no "${heading}" section`);
  let end = lines.findIndex((line, i) => i > start && line.startsWith("## "));
  if (end === -1) end = lines.length;
  const out = lines.slice(start, end);
  while (out.length > 0 && out[out.length - 1].trim() === "") out.pop();
  return out;
}

/**
 * `N. Title` for each numbered convention, e.g. `1. i18n`.
 *
 * @param {string[]} lines
 * @returns {string[]}
 */
export function conventionTitles(lines) {
  const titles = [];
  for (const line of sectionLines(lines, "## Conventions (non-negotiable)")) {
    const m = /^(\d+)\.\s+\*\*([^*]+)\*\*/.exec(line);
    if (m) titles.push(`${m[1]}. ${m[2]}`);
  }
  return titles;
}

/**
 * The full text of one projection, LF line endings.
 *
 * @param {string} canonical the text of .claude/CLAUDE.md
 * @param {{ file: string, frontmatter: string[] }} projection
 * @returns {string}
 */
export function projectGuidance(canonical, projection) {
  const lines = canonical.replace(/\r\n/g, "\n").split("\n");
  return [
    ...projection.frontmatter,
    `<!-- Generated by scripts/project-guidance.mjs from ${CANONICAL}. Do not edit by hand: change the canonical file, then run \`node scripts/project-guidance.mjs\`. -->`,
    "",
    "# personas-web: agent guidance",
    "",
    `The rules for this repository live in \`${CANONICAL}\`, which wins any conflict. This file is generated from it for agents other than Claude Code. It carries the Project and Commands sections word for word and an index of the conventions. Read the canonical file before you change code.`,
    "",
    ...sectionLines(lines, "## Project"),
    "",
    ...sectionLines(lines, "## Commands"),
    "",
    "## Conventions",
    "",
    `Each is a numbered item under "## Conventions (non-negotiable)" in \`${CANONICAL}\`, and the full rule is there:`,
    "",
    ...conventionTitles(lines),
    "",
  ].join("\n");
}

function main(argv) {
  const check = argv.includes("--check");
  const canonical = fs.readFileSync(path.join(REPO_ROOT, CANONICAL), "utf8");
  let stale = 0;
  for (const projection of PROJECTIONS) {
    const want = projectGuidance(canonical, projection);
    const target = path.join(REPO_ROOT, projection.file);
    const have = fs.existsSync(target) ? fs.readFileSync(target, "utf8").replace(/\r\n/g, "\n") : null;
    if (have === want) continue;
    if (check) {
      stale += 1;
      console.error(`${projection.file} is stale against ${CANONICAL}`);
    } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, want);
      console.log(`wrote ${projection.file}`);
    }
  }
  if (stale > 0) {
    console.error("run: node scripts/project-guidance.mjs");
    process.exitCode = 1;
  }
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main(process.argv.slice(2));
}
